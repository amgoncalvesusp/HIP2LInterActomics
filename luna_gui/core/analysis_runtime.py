_NOISY_HELPER_MARKERS = (
    "openbabel/__init__.py",
    '"import openbabel" is deprecated',
    "warnings.warn",
    "Module 'simplejson' not available",
)


def _clean_helper_text(text: str | None) -> str:
    """Remove noisy third-party warnings from helper output."""
    cleaned: list[str] = []
    for line in str(text or "").splitlines():
        stripped = line.strip()
        if not stripped:
            continue
        if any(marker in stripped for marker in _NOISY_HELPER_MARKERS):
            continue
        cleaned.append(line)
    return "\n".join(cleaned).strip()


def _helper_json_from_stdout(stdout: str | None) -> dict:
    for line in reversed(str(stdout or "").splitlines()):
        stripped = line.strip()
        if stripped.startswith("{") and stripped.endswith("}"):
            return json.loads(stripped)
    raise ValueError("helper stdout did not contain a JSON object")


def _helper_failure(result: subprocess.CompletedProcess, prefix: str = "Helper falhou") -> dict:
    try:
        parsed = _helper_json_from_stdout(result.stdout)
        if isinstance(parsed, dict) and parsed.get("error"):
            return parsed
    except Exception:
        pass
    detail_parts = [
        part
        for part in (_clean_helper_text(result.stderr), _clean_helper_text(result.stdout))
        if part
    ]
    detail = "\n".join(detail_parts).strip()
    if not detail:
        detail = "sem saida de erro relevante; apenas avisos conhecidos foram filtrados."
    code = int(result.returncode)
    if code < 0:
        signum = abs(code)
        try:
            signal_name = signal.Signals(signum).name
        except Exception:
            signal_name = f"signal {signum}"
        status = f"sinal {signum} ({signal_name})"
        if signum == 11:
            detail += (
                "\nO helper caiu dentro de uma biblioteca nativa durante a geração PSE "
                "do LUNA/PyMOL. Corrija a dependência nativa indicada pelo "
                "stderr/ambiente do luna-env."
            )
    else:
        status = f"exit {code}"
    return {"error": f"{prefix} ({status}):\n{detail[:2000]}"}


def _helper_invalid_output(result: subprocess.CompletedProcess) -> dict:
    detail_parts = [
        part
        for part in (_clean_helper_text(result.stdout), _clean_helper_text(result.stderr))
        if part
    ]
    detail = "\n".join(detail_parts).strip() or "sem saida relevante do helper."
    return {"error": f"Saida invalida do helper:\n{detail[:1000]}"}


def _fp_detail_cache_has_shell_levels(cached: dict | None) -> bool:
    feature_details = (cached or {}).get("feature_details") or {}
    if not feature_details:
        return True
    return all(
        isinstance(detail, dict) and "shell_level_counts" in detail
        for detail in feature_details.values()
    )


def _build_shell_level_only_fp_detail(wd: Path, ifp_type: str, output_path: Path) -> dict | None:
    """Build a non-crashing fp_detail fallback from fp_analysis metadata.

    Older GUI versions stored shell objects as pickles. Re-opening those objects
    can segfault inside native LUNA/OpenBabel/PyMOL dependencies, so this fallback
    only uses the already-safe JSON metadata. It preserves shell-level data for
    old projects; full interaction/residue detail is generated by current runs.
    """
    suffix = {value: key for key, value in IFP_SUFFIX_TO_TYPE.items()}.get(str(ifp_type).upper())
    if suffix is None:
        return None
    analysis_path = wd / "results" / "fingerprints" / f"fp_analysis_{suffix}.json"
    analysis = _load_cached_json(analysis_path)
    if not isinstance(analysis, dict):
        return None

    feature_details: dict[str, dict] = {}
    entry_index = analysis.get("entry_index") or {}
    if not isinstance(entry_index, dict):
        return None

    for entry_name, rows in entry_index.items():
        for row in rows or []:
            if not isinstance(row, dict) or "feature_id" not in row:
                continue
            try:
                feature_key = str(int(row.get("feature_id")))
            except Exception:
                feature_key = str(row.get("feature_id") or "").strip()
            if not feature_key:
                continue
            detail = feature_details.setdefault(
                feature_key,
                {
                    "interaction_counts": {},
                    "residue_counts": {},
                    "pair_counts": {},
                    "shell_level_counts": {},
                    "entries": {},
                },
            )
            entry_info = detail["entries"].setdefault(
                str(entry_name),
                {
                    "shell_count": 0,
                    "interaction_counts": {},
                    "residue_counts": {},
                    "pair_counts": {},
                    "shell_level_counts": {},
                },
            )
            breakdown = row.get("shell_level_breakdown") or {}
            if not isinstance(breakdown, dict):
                continue
            for raw_level, raw_count in breakdown.items():
                level = str(raw_level or "").strip()
                if not level:
                    continue
                try:
                    count = int(raw_count)
                except Exception:
                    count = 1
                detail["shell_level_counts"][level] = detail["shell_level_counts"].get(level, 0) + count
                entry_info["shell_level_counts"][level] = entry_info["shell_level_counts"].get(level, 0) + count
                entry_info["shell_count"] += count

    if not feature_details:
        return None

    payload = {
        "ifp_type": str(ifp_type).upper(),
        "feature_details": feature_details,
        "source": "fp_analysis_shell_levels_only",
        "detail_warning": (
            "Projeto antigo sem fp_detail completo. Reexecute o calculo com a versao atual "
            "para gerar contagens de interacao/residuo sem reabrir pickles de shells."
        ),
    }
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    return payload

