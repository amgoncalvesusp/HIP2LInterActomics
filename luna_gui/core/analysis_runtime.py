def _summary_from_residue_matrix(artifact: dict | None) -> dict | None:
    """Rebuild the lightweight statistics summary from the cached matrix."""
    if not isinstance(artifact, dict):
        return None
    entries = [str(value) for value in (artifact.get("entries") or [])]
    residues = [str(value) for value in (artifact.get("residues") or [])]
    matrices = artifact.get("matrix")
    if not entries or not isinstance(matrices, dict) or not matrices:
        return None

    interaction_counts: dict[str, int | float] = {}
    residue_counts: dict[str, int | float] = {label: 0 for label in residues}
    entry_counts: dict[str, dict[str, int | float]] = {entry: {} for entry in entries}
    active_entries: set[str] = set()

    def normalized(value: float) -> int | float:
        return int(round(value)) if abs(value - round(value)) < 1e-9 else value

    for interaction_type, rows in matrices.items():
        if not isinstance(rows, list):
            continue
        total = 0.0
        for row_index, row in enumerate(rows):
            if not isinstance(row, list):
                continue
            row_total = 0.0
            for column_index, raw_value in enumerate(row):
                try:
                    value = float(raw_value)
                except (TypeError, ValueError):
                    continue
                row_total += value
                if column_index < len(residues):
                    residue_counts[residues[column_index]] += value
            total += row_total
            if row_index < len(entries) and row_total:
                entry = entries[row_index]
                active_entries.add(entry)
                entry_counts[entry][str(interaction_type)] = normalized(row_total)
        interaction_counts[str(interaction_type)] = normalized(total)

    return {
        "entries": len(active_entries),
        "interaction_counts": interaction_counts,
        "residue_counts": {
            key: normalized(float(value))
            for key, value in residue_counts.items()
            if value
        },
        "entry_interaction_counts": entry_counts,
        "errors": [],
        "source": "residue_matrix.json",
    }


def _cache_analysis_summary(workdir: Path, result: dict) -> None:
    if result.get("error"):
        return
    output = workdir / "results" / "analysis_summary.json"
    cached_result = dict(result)
    cached_result["schema_version"] = ANALYSIS_SUMMARY_SCHEMA_VERSION
    cached_result["source_signature"] = _analysis_source_signature(workdir)
    temporary = output.with_name(f".{output.name}.part")
    try:
        output.parent.mkdir(parents=True, exist_ok=True)
        temporary.write_text(json.dumps(cached_result, indent=2, ensure_ascii=False), encoding="utf-8")
        temporary.replace(output)
    except OSError:
        temporary.unlink(missing_ok=True)


def _analysis_source_signature(workdir: Path) -> str:
    """Hash the residue matrix content and result-file metadata for cache invalidation."""
    digest = hashlib.sha256()
    results_dir = workdir / "results"
    matrix_path = results_dir / "residue_matrix.json"
    if matrix_path.exists():
        digest.update(b"residue_matrix.json\0")
        try:
            with matrix_path.open("rb") as handle:
                for chunk in iter(lambda: handle.read(1024 * 1024), b""):
                    digest.update(chunk)
        except OSError:
            pass
    try:
        result_files = sorted(
            {
                path
                for pattern in ("*.pkl.gz", "*.pkl")
                for path in results_dir.rglob(pattern)
            },
            key=lambda path: str(path).casefold(),
        )
    except OSError:
        result_files = []
    for path in result_files:
        try:
            stat = path.stat()
            relative = path.relative_to(workdir).as_posix()
            digest.update(f"{relative}\0{stat.st_size}\0{stat.st_mtime_ns}\0".encode("utf-8"))
        except (OSError, ValueError):
            continue
    return digest.hexdigest()


def _analysis_cache_is_current(cached: dict | None, workdir: Path) -> bool:
    if not isinstance(cached, dict) or cached.get("error"):
        return False
    return (
        int(cached.get("schema_version", 0) or 0) == ANALYSIS_SUMMARY_SCHEMA_VERSION
        and str(cached.get("source_signature") or "") == _analysis_source_signature(workdir)
    )


def _scaled_analysis_timeout(workdir: Path, requested_timeout: int) -> int:
    try:
        result_files = {
            str(path.resolve(strict=False))
            for pattern in ("*.pkl.gz", "*.pkl")
            for path in (workdir / "results").rglob(pattern)
        }
    except OSError:
        result_files = set()
    return max(int(requested_timeout), min(3600, 300 + (10 * len(result_files))))


def run_analysis(py_exe: str, workdir: str, timeout: int = 900) -> dict:
    wd = Path(workdir)
    cached = _load_cached_json(wd / "results" / "analysis_summary.json")
    if _analysis_cache_is_current(cached, wd):
        return cached
    residue_artifact = _load_cached_json(wd / "results" / "residue_matrix.json")
    matrix_summary = _summary_from_residue_matrix(residue_artifact)
    if matrix_summary is not None:
        _cache_analysis_summary(wd, matrix_summary)
        return _load_cached_json(wd / "results" / "analysis_summary.json") or matrix_summary
    if isinstance(cached, dict) and not cached.get("error"):
        # Preserve old projects that have only the lightweight summary, while
        # upgrading them so subsequent loads use the versioned cache contract.
        _cache_analysis_summary(wd, cached)
        return _load_cached_json(wd / "results" / "analysis_summary.json") or cached
    result = analysis_helper.run_analysis(
        py_exe,
        workdir,
        timeout=_scaled_analysis_timeout(wd, timeout),
    )
    if isinstance(result, dict):
        _cache_analysis_summary(wd, result)
    return result


